namespace FogSoft.Web.Infrastructure;

/// <summary>
/// Веб-аналог десктопного курсора ожидания (Globals.SetWaitCursor): пока идёт
/// долгая операция, оболочка (MainLayout) накрывает экран прозрачным слоем с
/// курсором ожидания и полосой прогресса.
///
/// Почему нужен явный вызов, а не «само». Данные в ядре читаются синхронно
/// (GetContent → DataAccessor), а Blazor Server отдаёт браузеру отрисовку
/// только когда обработчик события вернул управление. Синхронная загрузка
/// внутри обработчика означает, что браузер до конца запроса не получает
/// ничего — даже состояние «жду». <see cref="RunAsync"/> сначала включает
/// признак и отпускает circuit (Task.Yield), чтобы отрисовка со слоем ушла в
/// браузер, и только потом выполняет работу.
///
/// Слой блокирует мышь, а не только показывает ожидание (решение владельца
/// продукта 2026-09-22): клики во время запроса Blazor не теряет, а ставит в
/// очередь и выполняет после — второй «Применить» перечитал бы журнал ещё раз,
/// клик по строке открыл бы карточку уже в новом списке.
///
/// Слой накрывает всё окно, включая меню и открытые диалоги: сохранение карточки,
/// вызванной из другой карточки, и загрузка списка в диалоге выбора идут поверх
/// модального окна, и слой под ним был бы не виден.
///
/// Ожидание ответа пользователя в диалоге — не «занято»: под RunAsync
/// оборачивается только обращение к базе, сам показ диалога — никогда.
///
/// Scoped — свой на circuit: ожидание одной вкладки не должно накрывать другую.
/// </summary>
public sealed class BusyService
{
	// Счётчик, а не флаг: операции бывают вложенными (перечитать узел, а внутри —
	// список справа), и внутренняя не должна гасить слой раньше внешней.
	private int _depth;

	public bool IsBusy => _depth > 0;

	/// <summary>Сообщает оболочке, что нужно перерисоваться.</summary>
	public event Action? Changed;

	/// <summary>
	/// Выполнить синхронную работу под слоем ожидания. Ошибки работы не
	/// перехватываются — их показывает вызывающий экран, как и раньше.
	/// </summary>
	public Task RunAsync(Action work) =>
		RunAsync(() =>
		{
			work();
			return true;
		});

	/// <summary>То же, для работы с результатом (Update(), LoadPassportData() и т. п.).</summary>
	public async Task<T> RunAsync<T>(Func<T> work)
	{
		_depth++;
		if (_depth == 1)
			Changed?.Invoke();

		try
		{
			// Отпустить circuit: обработчик возвращает незавершённую задачу,
			// Blazor отрисовывает слой и отправляет его в браузер, а работа
			// продолжается следующей порцией на том же диспетчере.
			await Task.Yield();
			return work();
		}
		finally
		{
			_depth--;
			if (_depth == 0)
				Changed?.Invoke();
		}
	}
}
